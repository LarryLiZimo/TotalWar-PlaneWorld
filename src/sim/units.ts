export function unitDef(type: UnitType): UnitDef {
  return UNITS[type]
}

export function isInfantry(type: UnitType): boolean {
  return type === 'spear' || type === 'sword' || type === 'greatsword' || type === 'inquisitor'
}

export function isRangedInfantry(type: UnitType): boolean {
  return type === 'archer' || type === 'musket'
}

export function isCavalry(type: UnitType): boolean {
  return type === 'heavyCavalry' || type === 'lightCavalry' || type === 'general'
}
